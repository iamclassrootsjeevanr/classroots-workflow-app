#!/usr/bin/env python3
"""Fan out the single sources to every tool's native location.

  .agents/skills/*      -> .claude/skills/*, .cursor/skills/*
  .ai/mcp.json          -> .mcp.json (Claude Code), .cursor/mcp.json (Cursor),
                           .codex/config.toml (Codex, managed block only)

Usage: python3 .ai/bin/sync.py [--import]
  --import   first pull any servers already in .mcp.json / .cursor/mcp.json
             into .ai/mcp.json (one-time migration; never overwrites).
Stdlib only.
"""
import json
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
CANON = ROOT / ".ai" / "mcp.json"
SKILLS_SRC = ROOT / ".agents" / "skills"
SKILL_MIRRORS = [ROOT / ".claude" / "skills", ROOT / ".cursor" / "skills"]
CLAUDE_MCP = ROOT / ".mcp.json"
CURSOR_MCP = ROOT / ".cursor" / "mcp.json"
CODEX_TOML = ROOT / ".codex" / "config.toml"
BEGIN = "# >>> ai-continuity mcp (generated by .ai/bin/sync.py — edit .ai/mcp.json instead)"
END = "# <<< ai-continuity mcp"


def load_json(p):
    try:
        return json.loads(p.read_text(encoding="utf-8"))
    except FileNotFoundError:
        return None
    except json.JSONDecodeError as e:
        sys.exit(f"sync: {p.relative_to(ROOT)} is not valid JSON: {e}")


def write_json(p, data):
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(json.dumps(data, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")


# ---------- skills ----------
def sync_skills():
    if not SKILLS_SRC.is_dir():
        return []
    names = []
    for skill in sorted(d for d in SKILLS_SRC.iterdir() if (d / "SKILL.md").is_file()):
        for mirror in SKILL_MIRRORS:
            dest = mirror / skill.name
            if dest.is_symlink() or dest.is_file():
                dest.unlink()
            elif dest.is_dir():
                shutil.rmtree(dest)
            shutil.copytree(skill, dest)
        names.append(skill.name)
    return names


# ---------- MCP import ----------
def to_canonical(spec):
    out = {}
    if "command" in spec:
        out["command"] = spec["command"]
        if spec.get("args"):
            out["args"] = spec["args"]
        if spec.get("env"):
            out["env"] = spec["env"]
    elif "url" in spec:
        out["url"] = spec["url"]
        if spec.get("headers"):
            out["headers"] = spec["headers"]
    return out or None


def import_existing(canon):
    servers = canon.setdefault("servers", {})
    added = []
    for p in (CLAUDE_MCP, CURSOR_MCP):
        data = load_json(p) or {}
        for name, spec in (data.get("mcpServers") or {}).items():
            if name in servers:
                continue
            c = to_canonical(spec)
            if c:
                servers[name] = c
                added.append(f"{name} (from {p.relative_to(ROOT)})")
    return added


# ---------- MCP render ----------
def active(canon):
    for name, s in (canon.get("servers") or {}).items():
        if name.startswith("_") or not isinstance(s, dict) or s.get("enabled") is False:
            continue
        yield name, s


def render_json(canon, flavor):
    """flavor: 'claude' -> ${VAR}, 'cursor' -> ${env:VAR}"""
    ref = (lambda v: "${" + v + "}") if flavor == "claude" else (lambda v: "${env:" + v + "}")
    out = {}
    for name, s in active(canon):
        if "command" in s:
            e = {"command": s["command"], "args": s.get("args", [])}
            env = dict(s.get("env") or {})
            for var in s.get("env_passthrough") or []:
                env[var] = ref(var)
            if env:
                e["env"] = env
        elif "url" in s:
            e = {"type": "http", "url": s["url"]} if flavor == "claude" else {"url": s["url"]}
            headers = dict(s.get("headers") or {})
            if s.get("bearer_env"):
                headers["Authorization"] = "Bearer " + ref(s["bearer_env"])
            if headers:
                e["headers"] = headers
        else:
            continue
        out[name] = e
    return out


def toml_str(v):
    return json.dumps(v, ensure_ascii=False)  # JSON string escapes are valid TOML basic strings


def toml_key(k):
    return k if k.replace("_", "").replace("-", "").isalnum() else toml_str(k)


def toml_inline(d):
    return "{ " + ", ".join(f"{toml_key(k)} = {toml_str(v)}" for k, v in d.items()) + " }"


def render_codex(canon):
    lines = [BEGIN]
    for name, s in active(canon):
        lines.append(f"[mcp_servers.{toml_key(name)}]")
        if "command" in s:
            lines.append(f"command = {toml_str(s['command'])}")
            lines.append("args = [" + ", ".join(toml_str(a) for a in s.get("args", [])) + "]")
            if s.get("env"):
                lines.append(f"env = {toml_inline(s['env'])}")
            if s.get("env_passthrough"):
                lines.append("env_vars = [" + ", ".join(toml_str(v) for v in s["env_passthrough"]) + "]")
        elif "url" in s:
            lines.append(f"url = {toml_str(s['url'])}")
            if s.get("bearer_env"):
                lines.append(f"bearer_token_env_var = {toml_str(s['bearer_env'])}")
            if s.get("headers"):
                lines.append(f"http_headers = {toml_inline(s['headers'])}")
        lines.append("")
    lines.append(END)
    return "\n".join(lines) + "\n"


def write_codex(block):
    CODEX_TOML.parent.mkdir(parents=True, exist_ok=True)
    existing = CODEX_TOML.read_text(encoding="utf-8") if CODEX_TOML.exists() else ""
    if BEGIN in existing and END in existing:
        pre = existing.split(BEGIN)[0]
        post = existing.split(END, 1)[1].lstrip("\n")
        new = pre + block + (("\n" + post) if post else "")
    else:
        new = (existing.rstrip() + "\n\n" if existing.strip() else "") + block
    CODEX_TOML.write_text(new, encoding="utf-8")


def merge_mcp_servers(path, servers):
    data = load_json(path) or {}
    data["mcpServers"] = servers
    write_json(path, data)


def main():
    canon = load_json(CANON)
    if canon is None:
        sys.exit("sync: .ai/mcp.json missing — run the installer first.")
    if "--import" in sys.argv:
        added = import_existing(canon)
        if added:
            write_json(CANON, canon)
            print("sync: imported into .ai/mcp.json:", ", ".join(added))

    skills = sync_skills()
    claude = render_json(canon, "claude")
    merge_mcp_servers(CLAUDE_MCP, claude)
    merge_mcp_servers(CURSOR_MCP, render_json(canon, "cursor"))
    write_codex(render_codex(canon))

    print(f"sync: skills [{', '.join(skills) or 'none'}] -> .claude/skills, .cursor/skills")
    print(f"sync: MCP [{', '.join(claude) or 'none enabled'}] -> .mcp.json, .cursor/mcp.json, .codex/config.toml")


if __name__ == "__main__":
    main()
